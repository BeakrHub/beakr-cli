def _codex_text(content: Any) -> str:
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    return "\n\n".join(
        block["text"]
        for block in content
        if isinstance(block, dict)
        and block.get("type") in ("input_text", "output_text", "text")
        and isinstance(block.get("text"), str)
    )


_CODEX_CALLS = ("function_call", "custom_tool_call")
_CODEX_OUTPUTS = ("function_call_output", "custom_tool_call_output")


def _codex_tool_activity(payload: dict[str, Any], activity: SessionActivity) -> None:
    """Record one Codex tool call or result (``response_item`` or ``event_msg``)."""
    kind = payload.get("type")
    call_id = payload.get("call_id") or payload.get("id")
    if kind in _CODEX_CALLS:
        activity.call(call_id, payload.get("name"), payload.get("arguments", payload.get("input")))
    elif kind == "local_shell_call":
        action = payload.get("action") if isinstance(payload.get("action"), dict) else {}
        activity.call(call_id, "local_shell", {"command": action.get("command")})
    elif kind in _CODEX_OUTPUTS:
        activity.result(call_id, payload.get("output"))
    elif kind == "mcp_tool_call_end":
        # The event Codex records for an MCP call; its function_call, when the
        # rollout has one, was already counted under the same call id.
        invocation = payload.get("invocation")
        invocation = invocation if isinstance(invocation, dict) else {}
        if not activity.known(call_id):
            name = f"{invocation.get('server')}__{invocation.get('tool')}"
            activity.call(call_id, name, invocation.get("arguments"))
        result = payload.get("result")
        if isinstance(result, dict) and "Ok" in result:
            activity.result(call_id, result["Ok"])
        elif isinstance(result, dict):
            activity.result(call_id, result, is_error=True)


def parse_codex_session(path: str | Path) -> ParsedSession:
    """Parse a Codex rollout file (current ``response_item`` lines or older bare messages)."""
    path = Path(path)
    session_id: str | None = None
    cwd: str | None = None
    messages: list[dict[str, Any]] = []
    classifications: set[str] = set()
    activity = SessionActivity()
    # Codex marks the session, not each message: once the injected context is
    # dropped, a plain user message in a session a person drives is theirs.
    pending: list[tuple[str, str, Any]] = []
    for item in _read_lines(path):
        kind = item.get("type")
        payload = item.get("payload") if isinstance(item.get("payload"), dict) else None
        if kind in ("response_item", "event_msg") and payload is not None:
            _codex_tool_activity(payload, activity)
        if kind == "session_meta" and payload is not None:
            session_id = session_id or payload.get("id")
            cwd = cwd or payload.get("cwd")
            # A rollout can hold more than one session_meta (resumed or
            # forked); the conservative combination is taken below.
            classifications.add(classify_codex(payload.get("originator"), payload.get("source")))
            continue
        if kind == "response_item" and payload is not None:
            message = payload
        elif kind == "message":
            message = item
        else:
            # Older rollouts open with a bare meta line: {"id", "timestamp", ...}.
            if session_id is None and isinstance(item.get("id"), str) and "type" not in item:
                session_id = item["id"]
            continue
        if message.get("type") != "message" or message.get("role") not in ("user", "assistant"):
            continue
        text = _codex_text(message.get("content"))
        if message["role"] == "user" and text.lstrip().startswith(_CODEX_INJECTED_PREFIXES):
            continue
        pending.append((message["role"], text, item.get("timestamp")))
    classification = (
        HEADLESS
        if HEADLESS in classifications
        else HUMAN
        if classifications == {HUMAN}
        else UNKNOWN
    )
    user_author = AUTHOR_HUMAN if classification == HUMAN else AUTHOR_UNKNOWN
    for role, text, at in pending:
        if role == "assistant":
            author = AUTHOR_AGENT
        elif _CODEX_TAGGED.match(text):
            author = AUTHOR_UNKNOWN
        else:
            author = user_author
        _add_message(messages, role, text, at, author=author)
    return ParsedSession(
        session_id=str(session_id) if session_id else path.stem,
        messages=messages,
        files_touched=[],
        cwd=cwd,
        title=_title_from(messages),
        classification=classification,
        tools_used=activity.tools_used(),
        sources_read=activity.sources_read(),
    )


def parse_transcript(path: str | Path, client: str) -> ParsedSession:
    """Dispatch on the conversation ``client`` name used by the import API.

    A ChatGPT export holds many conversations; this returns it only when it
    holds exactly one (``chatgpt_export.parse_chatgpt_export`` reads them all).
    """
    if client == "codex":
        return parse_codex_session(path)
    if client == "claude-code":
        return parse_claude_code_transcript(path)
    if client in ("chatgpt-export", "chatgpt"):
        from beakr_cli.chatgpt_export import parse_chatgpt_export

        sessions = parse_chatgpt_export(path)
        if len(sessions) != 1:
            raise ValueError(
                f"This ChatGPT export holds {len(sessions)} conversations; import it with "
                "`beakr conversations import --client chatgpt-export --from-transcript <file>`."
            )
        return sessions[0]
    raise ValueError(
        f"No transcript parser for client '{client}'. Use claude-code, codex or chatgpt-export."
    )


def codex_session_files(codex_home: Path) -> list[Path]:
    """Every rollout file under ``<codex home>/sessions``, oldest path first."""
    root = codex_home / "sessions"
    if not root.is_dir():
        return []
    return sorted(root.rglob("rollout-*.jsonl"))


#: Each quoted request in a client-side summary is cut to this many characters.
_SUMMARY_QUOTE_CHARS = 280


def client_summary(session: ParsedSession) -> str | None:
    """A short, deterministic summary built on this machine from the transcript.

    Beakr keeps a summary and references by default, never the transcript
    (PROSE-392), and refuses an import that would keep nothing. When the person
    gives no ``--summary``, the CLI sends this instead: the session's title and
    its first and last requests, each cut short, labelled as a client-side
    summary so no one mistakes it for a model-written one. ``None`` when the
    session has no request to quote.
    """
    asks = [
        " ".join(str(m.get("content") or "").split())
        for m in session.messages
        if m.get("role") == "user" and str(m.get("content") or "").strip()
    ]
    if not asks:
        return None

    def cut(text: str) -> str:
        return text if len(text) <= _SUMMARY_QUOTE_CHARS else text[: _SUMMARY_QUOTE_CHARS - 1] + "…"

    parts = [f"Session: {session.title}."] if session.title else []
    parts.append(f'First request: "{cut(asks[0])}"')
    if len(asks) > 1:
        parts.append(f'Last request: "{cut(asks[-1])}"')
    parts.append(f"{len(session.messages)} messages. (Client-side summary by beakr-cli.)")
    return " ".join(parts)
