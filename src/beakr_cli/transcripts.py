def _claude_text(content: Any, files: list[str]) -> str:
    """Text blocks joined; tool_use inputs contribute to ``files`` only."""
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    parts = []
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") == "text" and isinstance(block.get("text"), str):
            parts.append(block["text"])
        elif block.get("type") == "tool_use" and block.get("name") in _FILE_WRITING_TOOLS:
            tool_input = block.get("input") if isinstance(block.get("input"), dict) else {}
            for key in _FILE_PATH_KEYS:
                value = tool_input.get(key)
                if isinstance(value, str) and value and value not in files:
                    files.append(value)
                    break
    return "\n\n".join(parts)


def classify_claude_code(
    entrypoints: set[str], prompt_sources: set[str], origin_kinds: set[str]
) -> str:
    """Classify a Claude Code session from the markers on its lines.

    Headless when any line came from the SDK entrypoints (``claude -p``, the
    Agent SDK) or any prompt was SDK-sent: one headless turn is enough, since
    a resumed session mixes both. Human only when every line is the terminal
    entrypoint and at least one main-thread prompt was typed by a person.
    Anything else -- no markers (older builds), or an entrypoint this
    version does not know -- is unknown, and is never treated as human.
    """
    if "sdk" in prompt_sources or any(
        e.startswith(_CLAUDE_HEADLESS_ENTRYPOINT_PREFIX) for e in entrypoints
    ):
        return HEADLESS
    typed = "typed" in prompt_sources or "human" in origin_kinds
    if entrypoints and entrypoints <= _CLAUDE_HUMAN_ENTRYPOINTS and typed:
        return HUMAN
    return UNKNOWN


def classify_codex(originator: Any, source: Any) -> str:
    """Classify a Codex session from its ``session_meta`` ``originator`` and ``source``.

    ``codex exec``, MCP-driven and subagent sessions are headless; the
    terminal TUI and the desktop/IDE app (``source`` ``cli`` or ``vscode``)
    are human; a rollout without these fields is unknown.
    """
    if originator in _CODEX_HEADLESS_ORIGINATORS:
        return HEADLESS
    if isinstance(source, dict):
        # {"subagent": {...}}: spawned by another session, not typed by a person.
        return HEADLESS
    if source in _CODEX_HEADLESS_SOURCES:
        return HEADLESS
    if source in _CODEX_HUMAN_SOURCES:
        return HUMAN
    return UNKNOWN


def _claude_user_author(item: dict[str, Any], text: str) -> str | None:
    """Who wrote one main-thread user record; ``None`` when the host wrote it.

    Human only on the record's own marker: a human session can still hold
    records the host wrote, so the session's classification is never enough.
    A record with no marker (older builds) is ``unknown``, never human.
    """
    prompt_source = item.get("promptSource")
    origin = item.get("origin")
    origin_kind = origin.get("kind") if isinstance(origin, dict) else None
    if any(item.get(flag) for flag in _CLAUDE_SYSTEM_FLAGS):
        return None
    if text.lstrip().startswith(_CLAUDE_SYSTEM_PREFIXES):
        return None
    if isinstance(prompt_source, str) and prompt_source not in _CLAUDE_TYPED_PROMPT_SOURCES:
        return None
    if isinstance(origin_kind, str) and origin_kind not in _CLAUDE_HUMAN_ORIGIN_KINDS:
        return None
    if prompt_source in _CLAUDE_TYPED_PROMPT_SOURCES or origin_kind in _CLAUDE_HUMAN_ORIGIN_KINDS:
        return AUTHOR_HUMAN
    return AUTHOR_UNKNOWN


def _claude_tool_activity(item: dict[str, Any], activity: SessionActivity) -> None:
    """Record the ``tool_use`` and ``tool_result`` blocks of one Claude Code line."""
    message = item.get("message")
    content = message.get("content") if isinstance(message, dict) else None
    if not isinstance(content, list):
        return
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") == "tool_use":
            activity.call(block.get("id"), block.get("name"), block.get("input"))
        elif block.get("type") == "tool_result":
            activity.result(
                block.get("tool_use_id"),
                block.get("content"),
                is_error=bool(block.get("is_error")),
            )


def parse_claude_code_transcript(path: str | Path) -> ParsedSession:
    """Parse a Claude Code session file."""
    path = Path(path)
    session_id: str | None = None
    cwd: str | None = None
    messages: list[dict[str, Any]] = []
    files: list[str] = []
    entrypoints: set[str] = set()
    prompt_sources: set[str] = set()
    origin_kinds: set[str] = set()
    activity = SessionActivity()
    for item in _read_lines(path):
        if session_id is None and isinstance(item.get("sessionId"), str):
            session_id = item["sessionId"]
        if cwd is None and isinstance(item.get("cwd"), str):
            cwd = item["cwd"]
        if isinstance(item.get("entrypoint"), str):
            entrypoints.add(item["entrypoint"])
        if item.get("type") in ("user", "assistant"):
            # Subagent (sidechain) calls count too: what a subagent read is
            # what the session's conclusions rest on.
            _claude_tool_activity(item, activity)
        if item.get("type") not in ("user", "assistant") or item.get("isMeta"):
            continue
        if item.get("isSidechain"):
            # Subagent turns are not the person's conversation.
            continue
        if item.get("type") == "user":
            if isinstance(item.get("promptSource"), str):
                prompt_sources.add(item["promptSource"])
            origin = item.get("origin")
            if isinstance(origin, dict) and isinstance(origin.get("kind"), str):
                origin_kinds.add(origin["kind"])
        message = item.get("message")
        if not isinstance(message, dict):
            continue
        role = message.get("role") or item["type"]
        if role not in ("user", "assistant"):
            continue
        text = _claude_text(message.get("content"), files)
        if role == "assistant":
            _add_message(messages, role, text, item.get("timestamp"), author=AUTHOR_AGENT)
            continue
        if text.lstrip().startswith(_CLAUDE_NOISE_PREFIXES):
            continue
        author = _claude_user_author(item, text)
        if author is None:
            # Written by the host, not the person: not part of what they said.
            continue
        _add_message(messages, role, text, item.get("timestamp"), author=author)
    return ParsedSession(
        session_id=session_id or path.stem,
        messages=messages,
        files_touched=files,
        cwd=cwd,
        title=_title_from(messages),
        classification=classify_claude_code(entrypoints, prompt_sources, origin_kinds),
        tools_used=activity.tools_used(),
        sources_read=activity.sources_read(),
    )


