"""Turn agent session files into conversation messages for import.

Two formats are read:

- Claude Code session JSONL (``~/.claude/projects/<dir>/<session>.jsonl``): one
  object per line; user and assistant turns carry ``type``, ``message.role``,
  ``message.content`` (a string or content blocks), ``timestamp``, ``sessionId``
  and ``cwd``.
- Codex rollout JSONL (``~/.codex/sessions/YYYY/MM/DD/rollout-*.jsonl``):
  ``session_meta`` and ``response_item`` lines, or (older builds) the message
  object itself on each line.

Only the human-readable text is kept as messages. Tool calls, tool results,
slash-command plumbing and harness-injected context are dropped from them: they
are not what the person and the agent said, and they would swamp the learning
that reads it. Tool calls are still read for two references
(``transcript_activity``): which tools the session used, and what Beakr
Knowledge it read, at which version.

A ChatGPT data export (``conversations.json``) is read by ``chatgpt_export``.

Every kept message carries an ``author``: ``agent`` for the
agent's turns, ``human`` only for a user turn the host marks as typed by a
person, ``unknown`` otherwise. A user-role record the host itself wrote -- a
background task's report, a compaction summary -- is dropped, not sent as the
person's words: imported-session learning may quote only ``human`` turns.
Parsing is defensive -- a line that does not parse or does not match is skipped,
because a half-written transcript from a live session is normal.
"""

from __future__ import annotations

import json
import re
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from beakr_cli.transcript_activity import SessionActivity

#: Longest title derived from the first user message.
_TITLE_CHARS = 120

#: Claude Code tools whose input names a file the session changed.
_FILE_WRITING_TOOLS = frozenset({"Edit", "Write", "MultiEdit", "NotebookEdit"})
_FILE_PATH_KEYS = ("file_path", "path", "notebook_path")

#: Claude Code writes slash-command and local-command plumbing as user turns.
_CLAUDE_NOISE_PREFIXES = (
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<system-reminder>",
    "Caveat: The messages below were generated by the user while running local commands",
    "[Request interrupted by user",
)

#: Codex injects these as user messages: context at the start of every
#: session, and host-written turns during it (plugin suggestions, heartbeats,
#: app pages opened from the desktop app).
_CODEX_INJECTED_PREFIXES = (
    "<environment_context>",
    "<user_instructions>",
    "<permissions instructions>",
    "# AGENTS.md instructions",
    "<recommended_plugins>",
    "<heartbeat>",
    "<external_codex_apps_open_page>",
)
#: Any other user message that opens with a markup tag is host plumbing this
#: version does not know: kept for context, never attributed to the person.
_CODEX_TAGGED = re.compile(r"\s*<[A-Za-z][A-Za-z0-9_\- ]{0,60}>")


#: How a session was driven, read from what the agent host wrote into it.
HUMAN = "human"
HEADLESS = "headless"
UNKNOWN = "unknown"

#: Who wrote one message (the import API's per-message ``author``).
AUTHOR_HUMAN = "human"
AUTHOR_AGENT = "agent"
AUTHOR_UNKNOWN = "unknown"

#: Claude Code records ``entrypoint`` on every line: ``cli`` for the terminal
#: TUI, ``sdk-cli`` for ``claude -p``, ``sdk-py``/``sdk-ts`` for the Agent SDK.
_CLAUDE_HUMAN_ENTRYPOINTS = frozenset({"cli"})
_CLAUDE_HEADLESS_ENTRYPOINT_PREFIX = "sdk"

#: Codex's ``session_meta`` records ``source`` (``cli``, ``vscode``, ``exec``,
#: ``mcp``, or ``{"subagent": ...}``) and ``originator`` (``codex-tui``,
#: ``codex_cli_rs``, ``Codex Desktop``, ``codex_exec``, ...).
_CODEX_HUMAN_SOURCES = frozenset({"cli", "vscode"})
_CODEX_HEADLESS_SOURCES = frozenset({"exec", "mcp"})
_CODEX_HEADLESS_ORIGINATORS = frozenset({"codex_exec"})

#: Claude Code marks who sent each main-thread user record: ``promptSource``
#: ``typed`` and ``origin.kind`` ``human`` for a person at the keyboard;
#: ``promptSource`` ``system`` or another origin (``task-notification`` for a
#: background task's report) for a record the host wrote itself.
_CLAUDE_TYPED_PROMPT_SOURCES = frozenset({"typed"})
_CLAUDE_HUMAN_ORIGIN_KINDS = frozenset({"human"})
#: Host-written user records that carry no ``promptSource``: background task
#: reports, and the summary a compacted session restarts from.
_CLAUDE_SYSTEM_PREFIXES = ("<task-notification>",)
_CLAUDE_SYSTEM_FLAGS = ("isCompactSummary", "isVisibleInTranscriptOnly")


@dataclass
class ParsedSession:
    session_id: str
    messages: list[dict[str, Any]] = field(default_factory=list)
    files_touched: list[str] = field(default_factory=list)
    cwd: str | None = None
    title: str | None = None
    #: ``human``, ``headless`` or ``unknown``: whether a person typed this
    #: session, from the host's own markers (``classify_*`` below). Only a
    #: ``human`` session can be sent as ``interactive``.
    classification: str = UNKNOWN
    #: ``[{"name", "count"}]``: the tools the session called.
    tools_used: list[dict[str, Any]] = field(default_factory=list)
    #: What it read from Beakr: ``{"page_id", "revision"?}`` or
    #: ``{"document_id", "version_id"?}`` (the import API's ``sources_read``).
    sources_read: list[dict[str, Any]] = field(default_factory=list)


def _read_lines(path: Path) -> Iterator[dict[str, Any]]:
    with path.open(encoding="utf-8", errors="replace") as handle:
        for raw in handle:
            raw = raw.strip()
            if not raw:
                continue
            try:
                item = json.loads(raw)
            except ValueError:
                continue
            if isinstance(item, dict):
                yield item


def _title_from(messages: list[dict[str, Any]]) -> str | None:
    for message in messages:
        if message["role"] == "user":
            text = " ".join(message["content"].split())
            return text if len(text) <= _TITLE_CHARS else text[: _TITLE_CHARS - 3] + "..."
    return None


def _add_message(
    messages: list[dict[str, Any]], role: str, text: str, at: Any = None, *, author: str
) -> None:
    text = text.strip()
    if not text:
        return
    message: dict[str, Any] = {"role": role, "content": text, "author": author}
    if isinstance(at, str) and at:
        message["at"] = at
    messages.append(message)


